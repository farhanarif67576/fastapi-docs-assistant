# ── DeepSeek Configuration ─────────────────────────────────────────────────────

DEEPSEEK_API_KEY = os.getenv("DEEPSEEK_API_KEY")
DEEPSEEK_BASE_URL = os.getenv("DEEPSEEK_BASE_URL", "https://api.deepseek.com")
DEEPSEEK_MODEL = os.getenv("DEEPSEEK_MODEL", "deepseek-v4-flash")

_openai_client = None

def get_openai_client():
    """Lazy-initialized OpenAI client to avoid import-time errors."""
    global _openai_client
    if _openai_client is None:
        if not DEEPSEEK_API_KEY:
            raise OpenAIError(
                "Missing credentials. Please set DEEPSEEK_API_KEY in .env or "
                "pass an api_key."
            )
        _openai_client = OpenAI(
            api_key=DEEPSEEK_API_KEY,
            base_url=DEEPSEEK_BASE_URL,
        )
    return _openai_client


# ── Text Index (TF-IDF) ────────────────────────────────────────────────────────

text_index = None


def load_text_index():
    """
    Load the in-memory TF-IDF text index from the pre-built pickle file.
    This doesn't require PostgreSQL to be running.
    The pickle was generated by `python -m app.ingest --mode standalone`.
    """
    global text_index
    
    # Load from pickle (standalone mode — no DB needed)
    idx, chunks = load_pickle_index()
    if idx is not None:
        text_index = idx
        return text_index
    
    # Fallback: try loading from pgvector (if DB is initialized)
    try:
        chunks = db.get_all_chunks()
        if chunks:
            text_index = TextIndex(
                text_fields=["title", "heading_path", "content", "section"],
                keyword_fields=["id"],
            )
            text_index.fit(chunks)
            print(f"Loaded text index with {len(chunks)} documents from pgvector")
            return text_index
    except Exception as e:
        print(f"⚠️  Could not load text index from pgvector: {e}")
    
    print("⚠️  No text index available. Run: python -m app.ingest --mode standalone")
    return None


# ── Search Functions ───────────────────────────────────────────────────────────

TEXT_BOOST = {
    "title": 3.0,
    "heading_path": 2.0,
    "content": 1.0,
    "section": 2.5,
}


def minsearch_search(query: str, boost: dict = None) -> List[Dict[str, Any]]:
    """
    Search using TF-IDF text index only.
    """
    if text_index is None:
        load_text_index()
    
    if text_index is None:
        return []
    
    if boost is None:
        boost = TEXT_BOOST
    
    results = text_index.search(
        query=query,
        filter_dict={},
        boost_dict=boost,
        num_results=20,
    )
    return results


def vector_search(query: str) -> List[Dict[str, Any]]:
    """
    Search using pgvector cosine similarity only.
    Falls back to empty results if pgvector is unavailable or not initialized.
    """
    try:
        embedder = get_embedder()
        query_embedding = embedder.embed_query(query)
        results = db.vector_search(query_embedding, limit=20)
        return results
    except Exception as e:
        # Vector search unavailable (pgvector not running, or embedder not installed)
        # This is expected in Docker where torch/onnx are not installed
        return []


def normalize_scores(results: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Normalize scores to [0, 1] range using min-max scaling.
    """
    if not results:
        return results
    
    scores = [r.get("_score", 0) for r in results]
    min_score = min(scores)
    max_score = max(scores)
    
    if max_score == min_score:
        for r in results:
            r["_score_normalized"] = 1.0
        return results
    
    for r in results:
        r["_score_normalized"] = (r.get("_score", 0) - min_score) / (max_score - min_score)
    
    return results


def hybrid_search(query: str, alpha: float = 0.5) -> List[Dict[str, Any]]:
    """
    Hybrid search combining TF-IDF (text) and pgvector (semantic) scores.
    
    hybrid_score = alpha * normalized_text_score + (1 - alpha) * normalized_vector_score
    
    Args:
        query: The search query
        alpha: Weight for text search (0 = pure vector, 1 = pure text, 0.5 = equal)
    
    Returns:
        List of documents with combined hybrid scores, sorted by relevance
    """
    # Get results from both search methods
    text_results = minsearch_search(query)
    vector_results = vector_search(query)
    
    # Normalize scores to [0, 1]
    text_results = normalize_scores(text_results)
    vector_results = normalize_scores(vector_results)
    
    # Build lookup dicts by document ID
    text_by_id = {r["id"]: r for r in text_results}
    vector_by_id = {r["id"]: r for r in vector_results}
    
    # Collect all unique document IDs
    all_ids = set(list(text_by_id.keys()) + list(vector_by_id.keys()))
    
    # Combine scores
    combined = []
    for doc_id in all_ids:
        text_score = text_by_id.get(doc_id, {}).get("_score_normalized", 0)
        vector_score = vector_by_id.get(doc_id, {}).get("_score_normalized", 0)
        
        hybrid_score = alpha * text_score + (1 - alpha) * vector_score
        
        # Get the document data (prefer text result for metadata)
        doc = text_by_id.get(doc_id) or vector_by_id.get(doc_id)
        if doc:
            result = doc.copy()
            result["_text_score"] = text_score
            result["_vector_score"] = vector_score
            result["_score"] = hybrid_score
            combined.append(result)
    
    # Sort by hybrid score descending
    combined.sort(key=lambda x: x["_score"], reverse=True)
    
    return combined[:10]


# ── Query Rewriting ────────────────────────────────────────────────────────────

QUERY_REWRITE_PROMPT = """
You are a search query optimizer for the FastAPI documentation knowledge base.
Rewrite the following user question into a concise, keyword-rich search query 
that will retrieve the most relevant documentation sections.

Rules:
- Keep it concise (5-15 words)
- Include key technical terms (e.g., 'CORS', 'dependency injection', 'TestClient')
- Remove conversational language
- Return ONLY the rewritten query, nothing else

User question: {question}
Optimized search query:
""".strip()


def rewrite_query(question: str) -> str:
    """
    Rewrite/expand a user question into a better search query using the LLM.
    
    Examples:
        "How do I add CORS?" → "FastAPI CORS middleware configuration CORSMiddleware"
        "What is DI?" → "FastAPI dependency injection Depends function parameters"
        "How do I test my API?" → "FastAPI TestClient pytest testing endpoints"
    """
    prompt = QUERY_REWRITE_PROMPT.format(question=question)
    try:
        rewritten, _ = llm(prompt, model=DEEPSEEK_MODEL)
        # Clean up the response
        rewritten = rewritten.strip().strip('"').strip("'").strip()
        return rewritten if rewritten else question
    except Exception as e:
        print(f"⚠️  Query rewriting failed: {e}. Using original query.")
        return question


