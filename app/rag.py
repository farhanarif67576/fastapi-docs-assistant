# ── Prompt Builder ─────────────────────────────────────────────────────────────

# Map prompt style names to templates
PROMPT_STYLES = {
    "concise": PROMPT_CONCISE,
    "detailed": PROMPT_DETAILED,
}

def build_prompt(query: str, search_results: list, prompt_style: str = "concise") -> str:
    """Build the RAG prompt from query and search results using the specified style.
    
    Args:
        query: The user's question
        search_results: List of retrieved document chunks
        prompt_style: Either "concise" or "detailed"
    
    Returns:
        Formatted prompt string
    """
    context = ""
    for doc in search_results:
        context += entry_template.format(
            title=doc.get("title", ""),
            section=doc.get("section", ""),
            content=doc.get("content", ""),
        ) + "\n\n"
    
    template = PROMPT_STYLES.get(prompt_style, PROMPT_CONCISE)
    prompt = template.format(question=query, context=context).strip()
    return prompt


# ── LLM Call (DeepSeek via Chat Completions) ───────────────────────────────────

def llm(prompt: str, model: str = DEEPSEEK_MODEL):
    """Call DeepSeek via Chat Completions API (OpenAI-compatible)."""
    client = get_openai_client()
    response = client.chat.completions.create(
        model=model,
        messages=[{"role": "user", "content": prompt}],
    )
    
    answer = response.choices[0].message.content
    token_stats = {
        "prompt_tokens": response.usage.prompt_tokens,
        "completion_tokens": response.usage.completion_tokens,
        "total_tokens": response.usage.total_tokens,
    }
    return answer, token_stats


# ── Relevance Evaluation ───────────────────────────────────────────────────────

def evaluate_relevance(question: str, answer: str):
    """Evaluate answer relevance using LLM-as-a-Judge."""
    prompt = evaluation_prompt_template.format(question=question, answer=answer)
    evaluation, tokens = llm(prompt)
    
    try:
        json_eval = json.loads(evaluation)
        return json_eval, tokens
    except json.JSONDecodeError:
        result = {"Relevance": "UNKNOWN", "Explanation": "Failed to parse evaluation"}
        return result, tokens


# ── Cost Calculation ───────────────────────────────────────────────────────────

def calculate_cost(model: str, tokens: dict) -> float:
    """Calculate approximate cost in USD for DeepSeek."""
    cost = 0.0
    model = model.lower()
    
    # DeepSeek pricing (approximate as of 2025)
    if "deepseek" in model:
        cost = (tokens["prompt_tokens"] * 0.14 + tokens["completion_tokens"] * 0.28) / 1_000_000
    
    return cost


# ── Full RAG Pipeline ──────────────────────────────────────────────────────────

def rag(
    query: str,
    model: str = DEEPSEEK_MODEL,
    alpha: float = 0.5,
    prompt_style: str = "concise",
    enable_rerank: bool = True,
    enable_rewrite: bool = True,
) -> dict:
    """
    Run the full RAG pipeline: query rewrite → hybrid search → re-rank → build prompt → DeepSeek LLM → evaluate.
    
    Args:
        query: The user's question
        model: The DeepSeek model to use
        alpha: Hybrid search weight (0 = pure vector, 1 = pure text)
        prompt_style: Either "concise" or "detailed"
        enable_rerank: Whether to apply cross-encoder re-ranking after search
        enable_rewrite: Whether to rewrite/expand the query before search
    
    Returns:
        Dict with answer, metadata, retrieval results, and evaluation
    """
    t0 = time()
    
    # Step 0: Query rewriting (improves search by expanding user query)
    search_query = query
    if enable_rewrite:
        search_query = rewrite_query(query)
        if search_query != query:
            print(f"   🔄 Rewritten query: '{query}' → '{search_query}'")
    
    # Step 1: Hybrid search (TF-IDF + pgvector)
    search_results = hybrid_search(search_query, alpha=alpha)
    
    # Step 1.5: Re-ranking (cross-encoder for more accurate ordering)
    if enable_rerank and search_results:
        try:
            reranker = get_reranker()
            if reranker.model is not None:
                search_results = reranker.rerank(query, search_results, top_k=10)
        except Exception as e:
            print(f"   ⚠️  Re-ranking skipped: {e}")
    
    # Step 2: Build prompt with context
    prompt = build_prompt(query, search_results, prompt_style=prompt_style)
    
    # Step 3: Call DeepSeek LLM
    answer, token_stats = llm(prompt, model=model)
    
    # Step 4: Evaluate relevance
    relevance, rel_token_stats = evaluate_relevance(query, answer)
    
    t1 = time()
    took = t1 - t0
    
    # Step 5: Calculate costs
    cost_rag = calculate_cost(model, token_stats)
    cost_eval = calculate_cost(model, rel_token_stats)
    total_cost = cost_rag + cost_eval
    
    return {
        "answer": answer,
        "model_used": model,
        "response_time": took,
        "relevance": relevance.get("Relevance", "UNKNOWN"),
        "relevance_explanation": relevance.get("Explanation", "Failed to parse"),
        "prompt_tokens": token_stats["prompt_tokens"],
        "completion_tokens": token_stats["completion_tokens"],
        "total_tokens": token_stats["total_tokens"],
        "eval_prompt_tokens": rel_token_stats["prompt_tokens"],
        "eval_completion_tokens": rel_token_stats["completion_tokens"],
        "eval_total_tokens": rel_token_stats["total_tokens"],
        "openai_cost": total_cost,
        "retrieved_chunks": [
            {
                "id": r["id"],
                "title": r["title"],
                "section": r["section"],
                "url": r["url"],
                "score": r["_score"],
            }
            for r in search_results[:5]  # Top 5 chunks
        ],
    }


# ── Search-only function for retrieval evaluation ──────────────────────────────

def search_only(query: str, method: str = "hybrid", alpha: float = 0.5) -> list:
    """
    Search only (no LLM) — used for retrieval evaluation.
    
    Args:
        query: The search query
        method: One of "text", "vector", or "hybrid"
        alpha: Hybrid search weight (only used if method="hybrid")
    
    Returns:
        List of document results
    """
    if method == "text":
        return minsearch_search(query)
    elif method == "vector":
        return vector_search(query)
    else:  # hybrid
        return hybrid_search(query, alpha=alpha)